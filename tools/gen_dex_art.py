#!/usr/bin/env python3
"""Generate firmware/main/dex_art.c: the Dex's icon and the speaker's portrait.

The icon is a 24x22 one-bit glyph like the other Games icons, of our own
drawing: a closed case with a lens. The portrait is docs/img/dex/speaker/
colour_102.png (the owner's art, 102 x 102), read 1:1 into RGB565 with no alpha.

    python3 tools/gen_dex_art.py           # writes firmware/main/dex_art.c
    python3 tools/gen_dex_art.py --check   # fails if it's out of date
    python3 tools/gen_dex_art.py --show    # the icon, in text
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "main" / "dex_art.c"
PORTRAIT = ROOT / "docs" / "img" / "dex" / "speaker" / "colour_102.png"
W, H = 24, 22


def icon():
    g = [[0] * W for _ in range(H)]
    def rect(x0, y0, x1, y1, v=255):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                g[y][x] = v
    def disc(cx, cy, r, v=255):
        for y in range(H):
            for x in range(W):
                if (x + .5 - cx) ** 2 + (y + .5 - cy) ** 2 <= r * r:
                    g[y][x] = v
    rect(4, 1, 19, 20)          # the case
    for x, y in ((4, 1), (19, 1), (4, 20), (19, 20)):   # its corners
        g[y][x] = 0
    rect(6, 14, 17, 14, 0)      # the seam where it opens
    disc(10, 7.5, 4.5, 0)       # the lens, in a ring
    disc(10, 7.5, 2.8)
    disc(9.2, 6.7, .9, 0)
    rect(16, 3, 17, 4, 0)       # a light
    rect(7, 17, 16, 18, 0)      # the keys
    return g


def rgb565(c):
    return (c[0] & 0xF8) << 8 | (c[1] & 0xFC) << 3 | c[2] >> 3


def generate():
    g = icon()
    im = Image.open(PORTRAIT).convert("RGB")
    if im.size != (102, 102):
        sys.exit(f"{PORTRAIT}: {im.size}, want 102 x 102")
    px = [im.getpixel((x, y)) for y in range(102) for x in range(102)]
    out = ["/* dex_art.c -- generated by tools/gen_dex_art.py; don't edit. */",
           '#include "palm_icons.h"', ""]
    out.append("static const uint8_t icon_dex_map[] = {" + ",".join(",".join(map(str, r)) for r in g) + "};")
    out += ["const lv_image_dsc_t icon_dex = {",
            f"  .header={{.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.flags=0,.w={W},.h={H},.stride={W},.reserved_2=0}},",
            f"  .data_size={W * H},.data=icon_dex_map }};", ""]
    out.append("/* the speaker: RGB565, row by row, in flash (DEX_PLAN.md 3) */")
    out.append("const uint16_t dex_speaker[102 * 102] = {")
    for y in range(102):
        out.append(",".join("0x%04x" % rgb565(px[y * 102 + x]) for x in range(102)) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


if "--show" in sys.argv:
    print("\n".join("".join("#" if v else "." for v in r) for r in icon()))
elif "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != generate():
        sys.exit("firmware/main/dex_art.c is out of date: run tools/gen_dex_art.py")
else:
    OUT.write_text(generate())
